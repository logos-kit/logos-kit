// Generates content/docs/reference/methods.mdx from the protocol's own
// schema (protocol/schema/*.json) and the wallet module's contract (.lidl),
// so the reference can't drift from what the wallet answers. Hand-written
// behaviour notes (scripts/method-notes.mjs) go under each method.
import fs from 'node:fs'
import path from 'node:path'
import { notes } from './method-notes.mjs'

const root = path.resolve(import.meta.dirname, '../../..')
const methods = JSON.parse(fs.readFileSync(path.join(root, 'protocol/schema/methods.json'), 'utf8'))
const intents = JSON.parse(fs.readFileSync(path.join(root, 'protocol/schema/intents.json'), 'utf8'))
const lidl = fs.readFileSync(
  path.join(root, 'modules/logos_kit_wallet/logos_kit_wallet.lidl'),
  'utf8',
)

const described = {}
for (const m of lidl.matchAll(/method (\w+)\([^)]*\) -> \w+ description "([^"]*)"/g))
  described[m[1]] = m[2]
const intentOf = {}
for (const i of intents.intents) intentOf[i.method] = i.intent

function type(s) {
  if (!s) return 'unknown'
  if (s.const !== undefined) return JSON.stringify(s.const)
  if (s.anyOf) return s.anyOf.map(type).join(' \\| ')
  if (s.type === 'array') return `${type(s.items)}[]`
  if (s.type === 'object') return s.properties ? 'object' : 'object'
  if (s.type === 'string' && s.pattern === '^[0-9]+$') return 'decimal string'
  return s.type || 'unknown'
}

function table(schema) {
  const props = schema?.properties || {}
  const keys = Object.keys(props)
  if (!keys.length) return '_No parameters._\n'
  const req = new Set(schema.required || [])
  let out = '| Name | Type | Required | Notes |\n|---|---|---|---|\n'
  for (const k of keys) {
    const p = props[k]
    const note = (p.description || '').replace(/\|/g, '\\|').replace(/\n/g, ' ')
    out += `| \`${k}\` | ${type(p)} | ${req.has(k) ? 'yes' : 'no'} | ${note} |\n`
  }
  return out
}

const esc = (s) => s.replace(/[{}<>]/g, (c) => `&#${c.charCodeAt(0)};`)
let out = `---
title: 'Wallet methods (LWS-0)'
description: 'Every method the Logos Kit wallet answers, generated from the protocol schema.'
---

{/* Generated by scripts/gen-reference.mjs from protocol/schema. Do not edit. */}

Protocol version **${methods.version}**. Reads are module calls on
\`logos_kit_wallet\` (\`logos.callModuleAsync\`); user-facing steps open the wallet
through a Basecamp intent. The QML and TypeScript SDKs wrap all of them: you
rarely call these by name.

`
for (const [name, m] of Object.entries(methods.methods)) {
  out += `## \`${name}\`\n\n`
  if (described[name]) out += `${esc(described[name])}\n\n`
  out += m.userFacing
    ? `**User-facing.** Open it with the \`${intentOf[name] || '(wallet UI only)'}\` intent; the wallet shows its own sheet.\n\n`
    : '**Read.** A module call; no prompt.\n\n'
  if (notes[name]) out += `### Behaviour\n\n${notes[name].trim()}\n\n`
  out += `### Params\n\n${table(m.params)}\n### Result\n\n`
  out += `\`${type(m.result)}\`${
    m.result?.properties
      ? `: ${Object.keys(m.result.properties)
          .map((k) => `\`${k}\``)
          .join(', ')}`
      : ''
  }\n\n`
  out += `<details>\n<summary>JSON Schema</summary>\n\n\`\`\`json\n${JSON.stringify({ params: m.params, result: m.result }, null, 2)}\n\`\`\`\n\n</details>\n\n`
}
const dir = path.join(import.meta.dirname, '../content/docs/reference')
fs.mkdirSync(dir, { recursive: true })
fs.writeFileSync(path.join(dir, 'methods.mdx'), out)
console.log(`wrote reference/methods.mdx: ${Object.keys(methods.methods).length} methods`)

// The capability matrix (scripts/capability-matrix.py at the repo root) as a
// docs page, so the docs show exactly what the checked-in matrix says.
const matrix = fs
  .readFileSync(path.join(root, 'docs/protocol/capability-matrix.md'), 'utf8')
  .replace(/^# .*\n+/, '')
fs.writeFileSync(
  path.join(dir, 'capabilities.mdx'),
  `---
title: 'Capability matrix'
description: 'Every LWS-0 method, intent and error code, and which ones the Logos Kit wallet and the conformance fake support.'
---

{/* Generated by scripts/gen-reference.mjs from docs/protocol/capability-matrix.md. Don't edit. */}

${matrix}`,
)
console.log('wrote reference/capabilities.mdx')
